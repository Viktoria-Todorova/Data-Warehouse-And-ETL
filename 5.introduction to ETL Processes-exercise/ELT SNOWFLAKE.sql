--perform transformation i the analysis layer


CREATE TABLE SALES_DATAVASE_NOV.ANALYTICS_LAYER.SALES_AGGREGATE AS
SELECT
    CUSTOMER_ID,
    DATE_TRUNC('month',ORDER_DATE) AS SALES_MONTH,
    COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMER_COUNT,
    SUM(AMOUNT * QUANTITY) AS TOTAL_REVENUE
FROM SALES_DATAVASE_NOV.CLEANSED_LAYER.CLEANED_SALES
GROUP BY CUSTOMER_ID,SALES_MONTH;

CREATE OR REPLACE MATERIALIZED VIEW SALES_DATAVASE_NOV.ANALYTICS_LAYER.MV_CUSTOMER_SEGMENT AS
SELECT
    CUSTOMER_ID,
    SUM(AMOUNT * QUANTITY) AS TOTAL_SPEND,
    CASE
        WHEN SUM(AMOUNT * QUANTITY) >10000 THEN 'HIGH VALUE'
        WHEN SUM(AMOUNT * QUANTITY) BETWEEN 5000 AND 10000 THEN 'MEDIUM VALUE'
        ELSE 'LOW VALUE'
    END AS CUSTOMER_CATEGORY
FROM SALES_DATAVASE_NOV.CLEANSED_LAYER.CLEANED_SALES
GROUP BY CUSTOMER_ID;

SELECT * FROM SALES_DATAVASE_NOV.ANALYTICS_LAYER.MV_CUSTOMER_SEGMENT;

-- CREATE FINAL REPORT FOR ANALYSIS

CREATE TABLE SALES_DATAVASE_NOV.ANALYTICS_LAYER.FINAL_SALES_REPORT AS
SELECT
    S.SALES_MONTH,
    C.CUSTOMER_CATEGORY,
    SUM(S.TOTAL_REVENUE) AS TOTAL_SALES
FROM SALES_DATAVASE_NOV.ANALYTICS_LAYER.SALES_AGGREGATE S
JOIN SALES_DATAVASE_NOV.ANALYTICS_LAYER.MV_CUSTOMER_SEGMENT C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY S.SALES_MONTH, C.CUSTOMER_CATEGORY
ORDER BY S.SALES_MONTH;


SELECT * FROM SALES_DATAVASE_NOV.ANALYTICS_LAYER.FINAL_SALES_REPORT;
