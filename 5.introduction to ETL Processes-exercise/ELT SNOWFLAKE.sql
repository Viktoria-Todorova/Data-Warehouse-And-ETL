CREATE TRANSIENT TABLE SALES_DATAVASE_NOV.CLEANSED_LAYER.CLEANED_SALES AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    TO_DATE(ORDER_DATE, 'DD-MM-YY') AS ORDER_DATE,
    TO_DECIMAL(AMOUNT,10,2) AS AMOUNT,
    TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
    PRODUCT_ID,
    TO_DECIMAL(DISCOUNT,10,2) AS DISCOUNT,
    TO_DECIMAL(PROFIT,10,2) AS PROFIT,
    COALESCE(SHIPPING_DAYS,0) AS SHIPPING_DAYS
FROM SALES_DATAVASE_NOV.RAW_LAYER.RAW_SALES
WHERE ORDER_DATE IS NOT NULL;

CREATE TRANSIENT TABLE SALES_DATAVASE_NOV.CLEANSED_LAYER.CLEANED_CUSTOMER AS
SELECT
    CUSTOMER_ID,
    LOWER(CUSTOMER_NAME) AS CUSTOMER_NAME,
    EMAIL,
    TO_DATE(SIGNUP_DATE,'YYYY-MM-DD') AS SIGNUP_DATE
FROM SALES_DATAVASE_NOV.RAW_LAYER.RAW_CUSTOMER;

CREATE TRANSIENT TABLE SALES_DATAVASE_NOV.CLEANSED_LAYER.CLEANED_PRODUCTS AS
SELECT
    PRODUCT_ID,
    LOWER(PRODUCT_NAME) AS PRODUCT_NAME,
    LOWER(CATEGORY) AS CATEGORY,
    TO_DECIMAL(PRICE,10,2) AS PRICE
FROM SALES_DATAVASE_NOV.RAW_LAYER.RAW_PRODUCTS
WHERE PRICE >0;

