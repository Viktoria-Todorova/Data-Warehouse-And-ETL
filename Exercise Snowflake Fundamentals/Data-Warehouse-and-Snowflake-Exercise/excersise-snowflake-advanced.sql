CREATE OR REPLACE ROW ACCESS POLICY CLEANSED_LAYER.CATEG_FILTER
    AS(CAT STRING())
    RETURNS BOOLEAN ->
    CASE
        WHEN UPPER(TRIM(CAT)) = UPPER(CURRENT_ROLE()) THEN TRUE
        WHEN CURRENT_ROLE() = 'FURNITURE' THEN TRUE
        ELSE FALSE
    END;

    --DROP ALL ACCESES
ALTER TABLE CLEANSED_LAYER.SALES_ORDERS_CLEAN
    DROP ALL ROW ACCESS POLICIES;

ALTER TABLE CLEANSED_LAYER.SALES_ORDERS_CLEAN
    ADD ROW ACCESS POLICY CLEANSED_LAYER.CATEG_FILTER
    ON(CATEGORY);

