--5. create cleansed table

CREATE OR REPLACE TRANSIENT TABLE CLEANSED_LAYER.SALES_ORDERS_CLEAN AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    TO_DATE(ORDER_DATE,'YYYY-MM-DD')AS ORDER_DATE,
    TO_DECIMAL(AMOUNT,10,2) AS AMOUNT,
    TO_DECIMAL(PROFIT,10,2) AS PROFIT,
    TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
    INITCAP(CATEGORY)AS CATEGORY,
    INITCAP(SUBCATEGORY) AS SUBCATEGORY
FROM RAW_LAYER.SALES_ORDERS_RAW;

SELECT * FROM CLEANSED_LAYER.SALES_ORDERS_CLEAN;

--6. MASK, RULE THAT CHANGES THE VALUE OF THE COLUMN DEPENDING ON THE PERSONS ROLE-- IT'S AN INFORMATION SECUTIRY

CREATE OR REPLACE MASKING POLICY CLEANSED_LAYER.MASKED_AMOUNT -- MASKED AMOUND THE NAME OF THE RULE
    AS (VAL DECIMAL(10,2))
    RETURNS DECIMAL(10,2) ->
    CASE
        WHEN CURRENT_ROLE() = 'FINANCE DEPARTMENT' THEN VAL -- CHECK THE ROLE
        ELSE NULL
    END;

ALTER TABLE CLEANSED_LAYER.SALES_ORDERS_CLEAN
    MODIFY COLUMN AMOUNT
    SET MASKING POLICY CLEANSED_LAYER.MASKED_AMOUNT;

    --7 CREATE TABLE FOR MV DROM BASE TABLE

    CREATE OR REPLACE TRANSIENT TABLE CLEANSED_LAYER.SALES_ORDERS_MV_READY AS
    SELECT 
    ORDER_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    ORDER_DATE,
    AMOUNT,
    PROFIT, 
    QUANTITY,
    CATEGORY,
    SUBCATEGORY
    FROM CLEANSED_LAYER.SALES_ORDERS_CLEAN;

    SELECT * FROM CLEANSED_LAYER.SALES_ORDERS_MV_READY; -- THE MASKING IS BEING USED HERE FRO THNE AMOUNT

    --8 PRE-COMPUTE TOTAL SALES PER CATEGORY FOR DAST BI ACCSESS
    CREATE OR REPLACE MATERIALIZED VIEW BUSINESS_LAYER.PROFIT_SUMMARY_MV AS 
    SELECT 
        CATEGORY,
        SUM(PROFIT) AS PROFIT
    FROM CLEANSED_LAYER.SALES_ORDERS_MV_READY
    GROUP BY CATEGORY;

    SELECT * FROM BUSINESS_LAYER.PROFIT_SUMMARY_MV;

    --9 CREATE A LOGICAL VIEW

    CREATE OR REPLACE VIEW PRESENTATION_LAYER.V_PROFIT_DASHBOARD AS
    SELECT
        CATEGORY,
        ROUND(PROFIT/SUM(PROFIT) OVER(),3) AS SHARE_OF_TOTAL
    FROM BUSINESS_LAYER.PROFIT_SUMMARY_MV
    ORDER BY PROFIT;

    SELECT * FROM PRESENTATION_LAYER.V_PROFIT_DASHBOARD;

